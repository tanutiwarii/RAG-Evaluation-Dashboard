from pydantic import BaseModel, Field
from typing import Optional
from datetime import datetime
import uuid


class EvalRequest(BaseModel):
    question: str = Field(..., min_length=5, description="The question asked to the RAG pipeline")
    answer: str = Field(..., min_length=1, description="The answer generated by your RAG pipeline")
    contexts: list[str] = Field(..., min_items=1, description="List of retrieved context chunks used to generate the answer")
    ground_truth: str = Field(..., min_length=1, description="The correct / expected answer")
    pipeline_name: Optional[str] = Field(default="default", description="Name of the RAG pipeline variant being evaluated")


class EvalScores(BaseModel):
    faithfulness: float = Field(..., ge=0, le=1, description="How grounded the answer is in the retrieved context")
    answer_relevancy: float = Field(..., ge=0, le=1, description="How relevant the answer is to the question")
    context_precision: float = Field(..., ge=0, le=1, description="How precise the retrieved context is")
    context_recall: float = Field(..., ge=0, le=1, description="How much of the ground truth is covered by retrieved context")
    answer_correctness: float = Field(..., ge=0, le=1, description="How correct the answer is compared to ground truth")


class EvalResponse(BaseModel):
    run_id: str
    pipeline_name: str
    question: str
    scores: EvalScores
    latency_ms: float
    timestamp: datetime


class BatchEvalRequest(BaseModel):
    pipeline_name: Optional[str] = Field(default="default")
    dataset_path: Optional[str] = Field(
        default="eval/test_dataset.json",
        description="Path to test_dataset.json"
    )


class BatchJobResponse(BaseModel):
    job_id: str
    message: str
    total_questions: int


class EvalHistoryItem(BaseModel):
    run_id: str
    pipeline_name: str
    question: str
    scores: EvalScores
    latency_ms: float
    timestamp: datetime

    class Config:
        from_attributes = True